-- Schema for a new, empty PostgreSQL database. This file is not yet wired to
-- the running server. Do not apply it to an existing database without a backup.
CREATE TABLE IF NOT EXISTS teachers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  pass_hash TEXT NOT NULL,
  salt TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_teachers_username_lower ON teachers (lower(username));
CREATE TABLE IF NOT EXISTS teacher_tokens (
  token TEXT PRIMARY KEY,
  teacher_id BIGINT NOT NULL REFERENCES teachers(id),
  created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS exams (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  access_code TEXT UNIQUE NOT NULL,
  settings TEXT NOT NULL DEFAULT '{}',
  created_at BIGINT NOT NULL,
  teacher_id BIGINT REFERENCES teachers(id)
);
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sections (
  id TEXT PRIMARY KEY,
  exam_id TEXT,
  ord INTEGER NOT NULL,
  title TEXT NOT NULL,
  instructions TEXT DEFAULT '',
  lock_after INTEGER NOT NULL DEFAULT 1,
  minutes INTEGER DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_sections_exam ON sections(exam_id);
CREATE TABLE IF NOT EXISTS questions (
  id TEXT PRIMARY KEY,
  section_id TEXT NOT NULL REFERENCES sections(id) ON DELETE CASCADE,
  ord INTEGER NOT NULL DEFAULT 0,
  kind TEXT NOT NULL,
  prompt TEXT NOT NULL,
  choices TEXT DEFAULT '[]',
  answer TEXT,
  points DOUBLE PRECISION NOT NULL DEFAULT 1,
  shuffle INTEGER NOT NULL DEFAULT 1,
  tags TEXT DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_questions_section ON questions(section_id, ord);
CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  exam_id TEXT,
  access_code TEXT NOT NULL,
  student_name TEXT NOT NULL,
  student_no TEXT NOT NULL,
  class_section TEXT DEFAULT '',
  status TEXT NOT NULL DEFAULT 'active',
  created_at BIGINT NOT NULL,
  started_at BIGINT,
  deadline BIGINT,
  last_seen BIGINT NOT NULL,
  order_seed INTEGER NOT NULL,
  answers TEXT NOT NULL DEFAULT '{}',
  section_index INTEGER NOT NULL DEFAULT 0,
  max_section INTEGER NOT NULL DEFAULT 0,
  cursor INTEGER NOT NULL DEFAULT 0,
  reloads INTEGER NOT NULL DEFAULT 0,
  ip TEXT DEFAULT '',
  user_agent TEXT DEFAULT '',
  submitted_at BIGINT,
  score DOUBLE PRECISION,
  max_score DOUBLE PRECISION,
  pending_manual DOUBLE PRECISION NOT NULL DEFAULT 0,
  violations INTEGER NOT NULL DEFAULT 0,
  flagged INTEGER NOT NULL DEFAULT 0,
  manual_notes TEXT DEFAULT '',
  manual_scores TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_sessions_code ON sessions(access_code, status);
CREATE INDEX IF NOT EXISTS idx_sessions_ident ON sessions(student_no, class_section);
CREATE INDEX IF NOT EXISTS idx_sessions_exam ON sessions(exam_id, status);
CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token TEXT NOT NULL,
  at BIGINT NOT NULL,
  type TEXT NOT NULL,
  detail TEXT DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_events_token ON events(token, at);

